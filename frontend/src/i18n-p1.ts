function mergeInto(target: MessageTree, source: MessageTree) {
  for (const [key, value] of Object.entries(source)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      const existing = target[key]
      if (!existing || typeof existing !== 'object' || Array.isArray(existing)) {
        target[key] = {}
      }
      mergeInto(target[key] as MessageTree, value as MessageTree)
      continue
    }
    target[key] = value
  }
}

export function applyP1Messages(messages: MessageTree) {
  mergeInto(messages, p1Messages as unknown as MessageTree)
}
